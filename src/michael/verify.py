"""Verify a draft's prose against the provisions actually retrieved for it.

``draft.citations_of()`` already guarantees the citation list: every pinpoint
under BASED ON came from a row retrieval returned. Nothing guaranteed the
*prose*. A clause could state a notice period of four weeks, cite s 117, and
be cited correctly while saying something s 117 does not say. Until now the
only thing standing between that and a practitioner was a human reading it.

This module closes that gap in three steps, two of which are code:

1. :func:`split_claims` - deterministic. Cut the draft into atomic claims and
   drop everything that asserts nothing: headings, rules, label lines, the
   generated scaffolding, the closing blocks, and any sentence carrying an
   unsupplied value.
2. :func:`build_prompt` and the :data:`JudgeFn` behind it - the only model
   call. A judge in a *different model family* from the drafting model is
   given the claims and the verbatim text of the retrieved provisions, and
   nothing else, and must answer in strict JSON.
3. :func:`validate_verdicts` - deterministic again, and the part that carries
   the guarantee. Every way the judge can fail - unparseable output, a missing
   claim, an invented verdict word, a provision id that is not in the
   retrieved set, a timeout, an unreachable provider, a same-family
   misconfiguration - resolves to UNSUPPORTED. There is no path through this
   module that turns a failure into a SUPPORTED claim.

Two things this module never does. It never rewrites the draft: annotation is
insertion only, at character offsets recorded during the split, so no drafted
word can be lost. And it never consults anything but the provisions handed to
it - no web, no second retrieval, no model memory. A judge asked "is this
supported" with access to its own recollection of the Fair Work Act will
confirm a claim the corpus does not hold, which is precisely the failure this
exists to catch.

Every unit-of-text decision here is behind :class:`ClaimUnit`. ``SENTENCE``
cuts statutory prose; ``PARAGRAPH`` cuts prose whose support is a judgment's
ratio, which no single sentence of it carries. ``split_claims`` takes either
one unit for the whole draft or a :data:`UnitSelector` that chooses per block,
so one draft can mix both. What a unit ruled on is recorded on the claim and
named in the judge prompt.

What the evidence *is* is behind :class:`Evidence` and
:data:`EVIDENCE_KINDS`: legislation supports a claim by stating it, a judgment
by what it decided, and :data:`JUDGE_INSTRUCTIONS` gives the judge both rules
and marks every provision with the kind it is.
"""

