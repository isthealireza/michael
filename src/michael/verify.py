class Evidence(Protocol):
    """What this module needs of a retrieved unit in order to judge against it.

    Widened from :class:`~michael.retrieve.RetrievedProvision` as the Phase 3
    handover asked. Verification depends on four things - an id, what kind of
    unit it is, its heading and its text - and on being able to render its
    pinpoint. It does not depend on scores, offsets or a jurisdiction, and
    typing it to the retrieval dataclass made it impossible to hand this
    module evidence from anywhere else, including a test fixture that is not a
    full retrieval row.
    """

    @property
    def provision_id(self) -> int: ...

    @property
    def unit_type(self) -> str: ...

    @property
    def heading(self) -> str: ...

    @property
    def text(self) -> str: ...

    def pinpoint(self) -> str: ...


#: How each unit type is described to the judge, and what SUPPORTED means for
#: it. See :data:`JUDGE_INSTRUCTIONS`.
EVIDENCE_KINDS: dict[str, str] = {
    "section": "legislation",
    "paragraph": "judgment",
    "order": "judgment",
    "document": "judgment",
}


def evidence_kind(provision: Evidence) -> str:
    """ "legislation" or "judgment" - which rule the judge applies to this unit.

    Unknown unit types fall back to "legislation", which is the stricter of
    the two: it requires the text to *state* the claim. An unrecognised unit
    is therefore harder to support, not easier.
    """
    return EVIDENCE_KINDS.get(provision.unit_type, "legislation")


def provision_id_of(provision: Evidence) -> str:
    """The id the judge cites a provision by.

    A string, not the database integer, because units have their own id
    spaces ("paragraph 47 of judgment 12") and a membership check that only
    understands integers would have to be rewritten for each.
    """
    return str(provision.provision_id)


JUDGE_INSTRUCTIONS = """\
You are verifying a draft legal document against the ONLY evidence available.

The PROVISIONS below are the complete and exclusive evidence. You have no other
source. Do not use your own knowledge of Australian law, of the Fair Work Act,
of any award, or of anything else. If a claim is true in the real world but the
provisions below do not say it, it is UNSUPPORTED. That is the point of this
task: a claim the provisions do not carry must be reported, however correct it
may be.

Each PROVISION below carries a kind, and the kind decides what SUPPORTED means
for it. Apply the rule for the kind of the provision you are relying on.

  kind="legislation" - a section or clause of an Act, Regulation or Award.
    SUPPORTED requires the provision's TEXT TO STATE the claim, including
    every number, party, condition and qualifier in it.

  kind="judgment" - a numbered paragraph of a court's reasons, or a court's
    orders. A judgment does not support a proposition by containing its words;
    it supports it by what the court DECIDED and the reasoning it gave for
    deciding it. So:
      SUPPORTED   - the claim states the rule the paragraph decided or
                    applied, or the fact the court found, even if the wording
                    differs.
      UNSUPPORTED - the paragraph only records a party's submission, quotes
                    another case or a statute without adopting it, or recites
                    a fact of that case which the claim then states as a rule.
    A claim that attributes to the court something the court was reporting
    rather than deciding is UNSUPPORTED, however closely the words match.

For EVERY claim you must return one object:
  {"claim_id": "<exact id>", "verdict": "SUPPORTED"|"PARTIAL"|"UNSUPPORTED"
                                        |"NOT_A_LEGAL_CLAIM",
   "provision_ids": ["<id>", ...], "reason": "<one sentence>"}

  SUPPORTED   - as defined above for the kind of provision relied on.
  PARTIAL     - the provisions carry part of it: the substance is there but a
                number, a party, a scope or a qualifier differs or is absent.
  UNSUPPORTED - the claim says something ABOUT THE LAW and nothing in the
                provisions carries it.
  NOT_A_LEGAL_CLAIM
              - the claim is not a proposition about the law at all, so no
                provision could support or contradict it. It is a term the
                parties agree between themselves, or a statement of fact about
                them or about this document.

                Examples: "The Employee must not disclose the Employer's
                confidential information" (a term of this agreement);
                "This document records the whole agreement between the
                parties" (a statement about the document); "The Employee must
                comply with the Employer's policies" (an obligation the
                employer creates, not one an Act imposes).

                NOT examples - these SAY SOMETHING ABOUT THE LAW and must be
                judged on the provisions: "The Employee is not entitled to
                paid annual leave"; "notice is given in accordance with the
                Fair Work Act"; "the employment is covered by the award";
                anything naming an Act, a section, a regulation or an award;
                anything asserting an entitlement, a prohibition, or what the
                law requires or permits.

                If you are unsure whether a claim is about the law, it IS
                about the law. Judge it. Do not use this verdict to avoid a
                difficult call - a claim wrongly put here is a claim nobody
                checks.

Rules:
- provision_ids must name provisions from the list below, by their exact id.
  Never invent an id. If you cannot name one, the verdict is UNSUPPORTED and
  provision_ids is [].
- SUPPORTED and PARTIAL require at least one provision_id.
- UNSUPPORTED and NOT_A_LEGAL_CLAIM take no provision_ids: [].
- A claim that names an obligation of the wrong party, a number the provisions
  do not state, an exception the provisions do not create, or a scope wider
  than the provisions grant, is not SUPPORTED.
- Return one object per claim, for every claim, and nothing else.

Answer with a single JSON object and no other text:
{"verdicts": [ ... ]}"""


def build_prompt(claims: Sequence[Claim], provisions: Sequence[Evidence]) -> str:
    """Assemble the judge prompt from the claims and the retrieved text only.

    The provision text is verbatim from retrieval. It is capped per provision
    at ``VERIFY_PROVISION_MAX_CHARS`` because a Fair Work Act volume runs to
    hundreds of thousands of characters and would not fit; a truncated
    provision can only *lose* support for a claim, so the cap fails in the
    closed direction, and the truncation is stated in the prompt so the judge
    does not treat an absence as a denial.
    """
    budget = settings().verify_provision_max_chars
    blocks: list[str] = []
    for provision in provisions:
        text = provision.text
        suffix = ""
        if len(text) > budget:
            text = text[:budget]
            suffix = "\n[TRUNCATED - this provision continues beyond what is shown]"
        blocks.append(
            f'<provision id="{provision_id_of(provision)}" '
            f'kind="{evidence_kind(provision)}">\n'
            f"citation: {provision.pinpoint()}\n"
            f"heading: {provision.heading}\n"
            f"text:\n{text}{suffix}\n"
            f"</provision>"
        )
    claim_lines = "\n".join(f"{c.claim_id} ({c.unit}): {c.text}" for c in claims)
    return (
        f"{JUDGE_INSTRUCTIONS}\n\n"
        f"PROVISIONS ({len(provisions)}):\n" + "\n\n".join(blocks) + "\n\n"
        f"CLAIMS ({len(claims)}):\n{claim_lines}\n"
    )


def judge_family(model: str) -> str:
    """The provider prefix of an OpenRouter model id - "anthropic", "deepseek"."""
    return model.split("/", 1)[0].strip().lower()


def check_judge_model(judge_model: str, drafting_model: str) -> None:
    """Refuse a judge from the drafting model's own family.

    A model is a poor auditor of its own output: it reproduces the same
    training-data recollection that produced the claim, and confirms it. The
    requirement that these differ is therefore enforced here rather than left
    to whoever edits .env, and a violation fails closed like any other judge
    failure.
    """
    if not judge_model.strip():
        raise JudgeError("VERIFY_JUDGE_MODEL is not set")
    if judge_family(judge_model) == judge_family(drafting_model):
        raise JudgeError(
            f"the judge model {judge_model!r} is from the same family as the drafting "
            f"model {drafting_model!r}; verification requires a different family, so "
            f"set VERIFY_JUDGE_MODEL to a model from another provider"
        )


def openrouter_judge(prompt: str) -> tuple[str, JudgeCall]:
    """Ask the configured judge. The only place this module reaches the network."""
    config = settings()
    check_judge_model(config.verify_judge_model, config.model)
    if not config.openrouter_api_key:
        raise JudgeError("OPENROUTER_API_KEY is not set, so the draft cannot be verified")

    started = time.monotonic()
    try:
        response = httpx.post(
            f"{config.openrouter_base_url.rstrip('/')}/chat/completions",
            headers={"Authorization": f"Bearer {config.openrouter_api_key}"},
            json={
                "model": config.verify_judge_model,
                "messages": [{"role": "user", "content": prompt}],
                # Determinism where the provider offers it: two runs over one
                # draft should not disagree about whether a clause is invented.
                "temperature": 0,
                "response_format": {"type": "json_object"},
                "usage": {"include": True},
            },
            timeout=config.verify_judge_timeout,
        )
    except httpx.HTTPError as exc:
        raise JudgeError(f"judge unreachable: {exc}") from exc
    seconds = time.monotonic() - started

    if response.status_code != 200:
        raise JudgeError(f"judge returned HTTP {response.status_code}: {response.text[:300]}")
    try:
        payload = response.json()
        content = payload["choices"][0]["message"]["content"]
    except (ValueError, KeyError, IndexError, TypeError) as exc:
        raise JudgeError(f"judge response had no message content: {exc}") from exc

    usage = payload.get("usage") or {}
    return str(content), JudgeCall(
        model=config.verify_judge_model,
        seconds=seconds,
        prompt_tokens=int(usage.get("prompt_tokens") or 0),
        completion_tokens=int(usage.get("completion_tokens") or 0),
        cost_usd=float(usage["cost"]) if usage.get("cost") is not None else None,
    )


# --- step 3: validate the judge's answer (code) ----------------------------

_FENCE = re.compile(r"^\s*```(?:json)?\s*|\s*```\s*$")


def _parse(raw: str) -> list[dict[str, Any]]:
    """The judge's verdict objects, or a :class:`JudgeError`."""
    text = _FENCE.sub("", (raw or "").strip())
    try:
        payload = json.loads(text)
    except ValueError as exc:
        raise JudgeError(f"judge did not return JSON: {exc}") from exc
    if isinstance(payload, dict):
        payload = payload.get("verdicts") or payload.get("claims")
    if not isinstance(payload, list):
        raise JudgeError("judge JSON had no 'verdicts' list")
    return [item for item in payload if isinstance(item, dict)]


def _ids(value: Any) -> tuple[str, ...]:
    """Normalise whatever the judge put in provision_ids to a tuple of strings."""
    if value is None:
        return ()
    if isinstance(value, str | int):
        value = [value]
    if not isinstance(value, list):
        return ()
    return tuple(str(item).strip() for item in value if str(item).strip())


def unsupported(claim_id: str, reason: str) -> Ruling:
    """The verdict every failure resolves to."""
    return Ruling(claim_id=claim_id, verdict="UNSUPPORTED", provision_ids=(), reason=reason)


def validate_verdicts(
    raw: str,
    *,
    claims: Sequence[Claim],
    retrieved_ids: Iterable[str],
) -> tuple[Ruling, ...]:
    """Turn the judge's raw output into one validated ruling per claim.

    Every rule here is a way of saying the same thing: a verdict is only worth
    something if it can be checked. A claim the judge did not answer, answered
    with a word that is not a verdict, or supported by an id that retrieval
    never returned, has not been verified - so it is UNSUPPORTED. Note the
    direction: an id outside the retrieved set condemns the whole claim rather
    than being dropped from its list, because a judge that cites a provision it
    was not given is reasoning from something other than the evidence, and
    nothing it said about that claim can be trusted.
    """
    known = {str(i) for i in retrieved_ids}
    try:
        items = _parse(raw)
    except JudgeError as exc:
        return tuple(unsupported(c.claim_id, str(exc)) for c in claims)

    by_id: dict[str, dict[str, Any]] = {}
    for item in items:
        claim_id = str(item.get("claim_id", "")).strip()
        if claim_id and claim_id not in by_id:
            by_id[claim_id] = item

    rulings: list[Ruling] = []
    for claim in claims:
        answer = by_id.get(claim.claim_id)
        if answer is None:
            rulings.append(unsupported(claim.claim_id, "the judge returned no verdict for it"))
            continue

        verdict = str(answer.get("verdict", "")).strip()
        if verdict not in VERDICTS:
            rulings.append(
                unsupported(claim.claim_id, f"the judge returned no usable verdict ({verdict!r})")
            )
            continue

        # The veto. A judge may say a claim is not about the law; it may not
        # say so about a claim that reads as law to the code. _asserts_law is
        # deliberately generous, so this disagreement is rare - and when it
        # happens the claim goes back to UNSUPPORTED rather than out of
        # verification, because the failure mode being guarded is a judge
        # excusing itself from a hard call. Code decides what must be checked;
        # the judge only decides whether what must be checked is supported.
        if verdict == NOT_A_LEGAL_CLAIM and _asserts_law(claim.text):
            rulings.append(
                unsupported(
                    claim.claim_id,
                    "the judge called this not a legal claim, but it asserts "
                    "something about the law, so it was checked as one and the "
                    "provisions do not carry it",
                )
            )
            continue

        reason = str(answer.get("reason", "")).strip() or "the judge gave no reason"
        ids = _ids(answer.get("provision_ids"))
        unknown = [i for i in ids if i not in known]
        if unknown:
            rulings.append(
                unsupported(
                    claim.claim_id,
                    "the judge cited "
                    + ", ".join(repr(i) for i in unknown)
                    + ", which retrieval did not return, so its reasoning was not "
                    "confined to the retrieved provisions",
                )
            )
            continue
        if verdict == NOT_A_LEGAL_CLAIM and ids:
            rulings.append(
                unsupported(
                    claim.claim_id,
                    "the judge named a provision while saying the claim is not "
                    "a legal claim, which cannot both be true",
                )
            )
            continue
        if verdict not in ("UNSUPPORTED", NOT_A_LEGAL_CLAIM) and not ids:
            rulings.append(
                unsupported(
                    claim.claim_id,
                    f"the judge answered {verdict} without naming a provision",
                )
            )
            continue

        rulings.append(
            Ruling(claim_id=claim.claim_id, verdict=verdict, provision_ids=ids, reason=reason)
        )
    return tuple(rulings)


# --- the whole thing -------------------------------------------------------


#: Words that mark a sentence as saying something about the LAW rather than
#: about these parties. Deliberately generous: a claim matching any of them is
#: judged even if it also carries a supplied value, so the set-aside below can
#: only ever narrow what is skipped, never what is checked.
_ASSERTS_LAW = re.compile(
    r"\b(?:"
    r"entitled|entitlement|entitlements|obliged|obligation|"
    r"must|required|requires|prohibited|unlawful|lawful|"
    r"complies|compliance|governed\s+by|in\s+accordance\s+with|"
    r"under\s+(?:the\s+|that\s+)?(?:Act|Regulations?|Award)|"
    r"section\s+\d|s\s+\d|Sch\s+\d|cl\s+\d|"
    r"Fair\s+Work|National\s+Employment|Modern\s+Award|award|"
    r"legislation|statute|statutory|casual\s+conversion|serious\s+misconduct"
    r")\b",
    re.IGNORECASE,
)


#: A supplied value shorter than this is ignored when deciding whether a
#: claim rests on the requester's own words: too short to be distinctive,
#: and a coincidental match would silently remove a claim from checking.
_MIN_INSTRUCTED_VALUE = 4


def _asserts_law(text: str) -> bool:
    """Does this claim say something about the law, not just about the parties?"""
    return bool(_ASSERTS_LAW.search(text))


def _set_aside_instructed(
    claims: tuple[Claim, ...], values: Sequence[str]
) -> tuple[tuple[Claim, ...], tuple[Claim, ...]]:
    """Split claims into those to judge and those resting on a supplied value.

    A claim is set aside only when it BOTH overlaps a supplied value AND says
    nothing about the law. Both conditions, so the narrowing cannot swallow a
    legal proposition that happens to sit beside a filled placeholder - which
    is how a scope heuristic fails open, and why the runner-up design (judge
    only sentences carrying a statutory marker) was rejected outright.
    """
    # Matched on the value, not on where it landed. split_claims re-anchors
    # offsets against a body with scaffolding blanked, and on the real template
    # only 4 of 14 claims came back with offsets matching the text they were
    # split from - so an overlap test on character spans agreed by luck. A
    # supplied value is in the claim's own text whatever the offsets do.
    #
    # Short values are ignored: a one- or two-character fact would match half
    # the draft by coincidence, and a coincidence here removes a claim from
    # verification, which is the direction that must never happen by accident.
    supplied = [v.strip() for v in values if len(v.strip()) >= _MIN_INSTRUCTED_VALUE]
    if not supplied:
        return claims, ()
    judged: list[Claim] = []
    aside: list[Claim] = []
    for claim in claims:
        rests_on_supplied = any(value in claim.text for value in supplied)
        if rests_on_supplied and not _asserts_law(claim.text):
            aside.append(claim)
        else:
            judged.append(claim)
    return tuple(judged), tuple(aside)


def verify_draft(
    draft_text: str,
    *,
    provisions: Sequence[Evidence],
    judge: JudgeFn | None = None,
    unit: ClaimUnit | UnitSelector = SENTENCE,
    instructed_values: Sequence[str] = (),
) -> Verification:
    """Check every claim in ``draft_text`` against ``provisions`` and nothing else.

    Never raises. Every failure - no provisions, an unreachable judge, a
    same-family judge, unparseable JSON - comes back as UNSUPPORTED rulings
    carrying the reason, because a draft that could not be verified must not
    read as a draft that passed.

    ``instructed_values`` are the values the requester supplied (see
    :attr:`michael.draft.Draft.instructed_values`). A claim resting on one is
    set aside rather than judged: "Payment is made fortnightly" is not a
    proposition the corpus can support or contradict, because fortnightly is
    what the requester said, so judging it can only ever return UNSUPPORTED.
    On the casual-contract template that was 11 of 24 claims, and a reader who
    finds two thirds of OPEN ITEMS full of unsupported party data stops reading
    the third that matters.

    This cannot fail open. The test is the presence of a supplied value inside
    the claim, not a guess about what the claim means: a sentence asserting
    something about the law carries no supplied value and is still judged, and
    a claim that both rests on a supplied value AND asserts law is still
    judged, because the span test is not what decides it - see
    ``_asserts_law``.
    """
    claims, skipped = split_claims(draft_text, unit=unit)
    claims, instructed = _set_aside_instructed(claims, instructed_values)
    try:
        judge_model = settings().verify_judge_model
    except ConfigError as exc:  # pragma: no cover - settings() is resolved by now
        judge_model = "(unconfigured)"
        return Verification(
            claims=claims,
            rulings=tuple(unsupported(c.claim_id, str(exc)) for c in claims),
            judge_model=judge_model,
            skipped_unsupplied=skipped,
            instructed=instructed,
        )

    if not claims:
        # The no-template outline lands here: it is scaffolding and
        # placeholders by design, and holds no drafted prose to check. Said
        # out loud, because "0 claims checked" with no explanation reads as
        # verification having failed rather than having had nothing to do.
        return Verification(
            claims=(),
            rulings=(),
            judge_model=judge_model,
            skipped_unsupplied=skipped,
            instructed=instructed,
            notes=(
                "This draft contains no verifiable claim: every line of it is a "
                "heading, a label, generated scaffolding, or a value not supplied.",
            ),
        )

    if not provisions:
        # No evidence exists, so no claim can be supported. Deterministic, and
        # it spends nothing: asking a judge to rule against an empty corpus
        # buys a round trip to reach the answer already known here.
        return Verification(
            claims=claims,
            rulings=tuple(
                unsupported(c.claim_id, "no provisions were retrieved, so nothing supports it")
                for c in claims
            ),
            judge_model=judge_model,
            skipped_unsupplied=skipped,
            instructed=instructed,
            notes=("Retrieval returned no provisions; every claim is unsupported by definition.",),
        )

    call: JudgeCall | None = None
    try:
        raw, call = (judge or openrouter_judge)(build_prompt(claims, provisions))
    except JudgeError as exc:
        return Verification(
            claims=claims,
            rulings=tuple(
                unsupported(c.claim_id, f"verification failed closed: {exc}") for c in claims
            ),
            judge_model=judge_model,
            skipped_unsupplied=skipped,
            instructed=instructed,
            call=JudgeCall(model=judge_model, seconds=0.0, error=str(exc)),
            notes=(f"The judge could not be used: {exc}",),
        )

    rulings = validate_verdicts(
        raw, claims=claims, retrieved_ids=[provision_id_of(p) for p in provisions]
    )
    return Verification(
        claims=claims,
        rulings=rulings,
        judge_model=call.model or judge_model,
        skipped_unsupplied=skipped,
        instructed=instructed,
        call=call,
    )


# --- output: mark, list, and report ----------------------------------------

VERIFICATION_NOTICE = (
    "Verification is automated. It checks each claim above against the text of "
    "the provisions retrieved for this draft and nothing else. It does not "
    "replace review by an admitted Australian legal practitioner, and a claim "
    "marked SUPPORTED has been matched to a provision, not approved."
)


def annotate(draft_text: str, verification: Verification) -> str:
    """Mark every flagged claim inline. Insertion only - nothing is removed.

    Markers are written back at the offsets recorded during the split, in
    reverse order so an earlier insertion cannot move a later one. The marker
    carries the claim id alone; the reason is long and belongs in OPEN ITEMS,
    where a practitioner reads it, rather than wedged into a contract clause.
    """
    flagged = {r.claim_id: r for r in verification.flagged}
    edits = sorted(
        (
            (claim.end, f" [{flagged[claim.claim_id].verdict}: {claim.claim_id}]")
            for claim in verification.claims
            if claim.claim_id in flagged
        ),
        reverse=True,
    )
    out = draft_text
    for at, marker in edits:
        out = out[:at] + marker + out[at:]
    return out


def open_items(verification: Verification) -> tuple[str, ...]:
    """One line per flagged claim, with its reason, for the OPEN ITEMS block."""
    lines: list[str] = []
    for ruling in verification.flagged:
        claim = verification.claim(ruling.claim_id)
        quoted = (claim.text if claim else "").strip()
        if len(quoted) > 160:
            quoted = quoted[:157].rstrip() + "..."
        lines.append(f'[{ruling.verdict}: {ruling.claim_id}] "{quoted}" - {ruling.reason}')
    return tuple(lines)


def section(verification: Verification) -> str:
    """The VERIFICATION block: what was checked, by what, and how it came out."""
    counts = verification.counts
    lines = [
        "## VERIFICATION",
        "",
        f"- Claims checked: {len(verification.claims)}",
        f"- SUPPORTED: {counts['SUPPORTED']}",
        f"- PARTIAL: {counts['PARTIAL']}",
        f"- UNSUPPORTED: {counts['UNSUPPORTED']}",
        f"- Not a claim about the law (a term of this agreement): {counts['NOT_A_LEGAL_CLAIM']}",
        f"- Not checked (value not supplied, see OPEN ITEMS): {verification.skipped_unsupplied}",
        f"- Not checkable against the corpus (your instructions, not law): "
        f"{len(verification.instructed)}",
        f"- Judge model: {verification.judge_model}",
    ]
    lines += [f"- {note}" for note in verification.notes]
    lines += ["", VERIFICATION_NOTICE]
    return "\n".join(lines)


def annotate_draft(draft: Draft, verification: Verification) -> Draft:
    """Fold a verification into a draft: markers inline, reasons in OPEN ITEMS.

    Returns a new :class:`~michael.draft.Draft`. The body is only ever added
    to, and ``open_items`` - the ``[MISSING]`` list the acceptance suite is
    written against - is left exactly as it was; verification adds its own
    lines below it.
    """
    return replace(
        draft,
        body=annotate(draft.body, verification),
        verification_section=section(verification),
        verification_items=open_items(verification),
    )
