Verdict = Literal["SUPPORTED", "PARTIAL", "UNSUPPORTED", "NOT_A_LEGAL_CLAIM"]

#: The only four words a judge may answer with. Anything else - "PARTIALLY",
#: "supported", "YES" - is not one of these and is therefore a failure, which
#: resolves to UNSUPPORTED. Accepting near-misses would mean guessing what the
#: judge meant, and a guess is the thing this module exists to remove.
VERDICTS: tuple[Verdict, ...] = (
    "SUPPORTED",
    "PARTIAL",
    "UNSUPPORTED",
    "NOT_A_LEGAL_CLAIM",
)

#: The fourth verdict, and why a judge is allowed to reach it.
#:
#: A drafted contract is mostly not propositions about the law. "The Employee
#: must not disclose the Employer's confidential information" is a term the
#: parties agree, not something the Fair Work Act says, and no provision will
#: ever support it. Judged against legislation it comes back UNSUPPORTED - true
#: in a useless sense, and on the casual-contract template 18 of 19 claims came
#: back that way, which buries the ones that are real defects.
#:
#: Code cannot draw this line. "must" appears in "the Act requires" and in "this
#: contract requires" alike, and a lexical guess that gets it wrong removes a
#: genuine legal claim from checking. A judge can read the intent; so it may say
#: so, under a veto it does not control - see :func:`validate_verdicts`.
NOT_A_LEGAL_CLAIM = "NOT_A_LEGAL_CLAIM"

#: Verdicts that put the claim in front of a human.
FLAGGED: frozenset[str] = frozenset({"PARTIAL", "UNSUPPORTED"})

#: Headings that ``draft.py`` appends after the drafted body. Everything from
#: the first of these onwards is generated by code and is not prose anyone
#: needs checked against a provision - the citation list is already guaranteed
#: by ``citations_of``, and the closing blocks are fixed text.
TRAILING_HEADINGS = (
    "## BASED ON",
    "## VERIFICATION",
    "## OPEN ITEMS",
    "## VERIFY BEFORE USE",
)

MIN_CLAIM_WORDS = 5
"""Below this a fragment is a label, a heading remnant or a stub, not an
assertion about the law. Set low on purpose: "The notice period is 5 weeks"
is six words and is exactly the kind of wrong number that must be caught, so
the floor has to sit under it rather than at a comfortable prose length."""

_SENTENCE_END = re.compile(r"(?<=[.!?])(?=\s)")

_HEADING = re.compile(r"^\s*#{1,6}\s")
_RULE = re.compile(r"^\s*(?:-{3,}|\*{3,}|_{3,})\s*$")
_BOLD_FIELD = re.compile(r"^\s*\*\*[^*]+:\*\*")
"""The template's party-field convention: ``**Employer:** Acme Pty Ltd of ...``
That is an identification, not a claim about the law, and it is the one line
shape in the corpus of templates that reliably carries a party name."""

_LIST_MARKER = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+")

_GENERATED_LINE = re.compile(
    r"^[ \t]*(?:"
    # The metadata header and the clause skeleton that
    # draft.outline_without_template() writes.
    r"(?:Request|Domain):\s"
    r"|No template in templates/"
    r"|The outline below is"
    r"|No provisions were retrieved for this request"
    r"|-\s*(?:Party [AB]|Commencement"
    # "Nearest retrieved provision" for legislation; "Nearest retrieved
    # paragraph" and "Nearest retrieved orders" for a judgment, which
    # draft.outline_without_template() writes so the line names the unit it
    # actually cites.
    r"|Nearest retrieved (?:provision|paragraph|orders)|Operative words|Source"
    r"|Clause to be drafted)\b"
    r")",
    re.MULTILINE,
)
"""Whole lines that ``draft.py`` writes itself, matched by their literal text.

These are excluded unconditionally, without the statutory-reference guard
below, and that is the difference between them and template prose: code wrote
them, so code knows they assert nothing. The outline's "Nearest retrieved
provision" line names an Act in every case - the guard would keep every one of
them - and yet it asserts nothing a judge could rule on. The pinpoint it
carries is already guaranteed by ``draft.citations_of``, and the quote beside
it by ``output_check.citation_fidelity``.

They are blanked rather than deleted (see :func:`_verifiable_body`) so the
character offsets annotation writes back to stay exact."""

_DOCUMENT_SUBJECT = re.compile(
    r"^(?:"
    # Savings and entire-agreement clauses, and the compliance disclaimer
    # MICHAEL.md requires. These assert something about this document, not
    # about the law, so no provision can support or contradict them.
    r"nothing in (?:this|the) (?:document|contract|agreement|outline|draft)\b"
    r"|(?:this|the) (?:document|contract|agreement|outline|draft|template)\b"
    r")",
    re.IGNORECASE,
)
"""A sentence of *template prose* whose subject is the artefact, not the law.

Narrow by construction, and guarded by :data:`_LEGAL_REFERENCE` below: the
failure direction that matters is excluding a claim that should have been
checked, so a sentence that looks self-referential but names a statute is
kept and judged anyway. Unlike :data:`_GENERATED_LINE` this is a shape rule
applied to prose nobody in this repository wrote, so it errs open."""

_LEGAL_REFERENCE = re.compile(
    r"\bAct\b|\bRegulations?\b|\bAward\b|\bNational Employment Standards\b"
    r"|\bs\.?\s?\d|\bsection\s+\d|\bSch(?:edule)?\.?\s*\d"
    # Case law. A medium-neutral citation ("[2024] HCA 1", "[2020] FCA 1492"),
    # a report-series citation ("(2023) 277 CLR 1"), and an AGLC paragraph
    # pinpoint ("at [12]"). Without these, a sentence whose subject is the
    # document and whose content is a claim about an authority - "This
    # outline follows Muir v Open Brethren [1956] HCA 14 at [2]" - is dropped
    # by _DOCUMENT_SUBJECT before any judge sees it, which is the one failure
    # direction that rule is written to avoid.
    r"|\[\d{4}\]\s*[A-Z][A-Za-z]{1,7}\s*\d"
    r"|\(\d{4}\)\s*\d+\s*[A-Z]{2,6}\s*\d"
    r"|\bat\s+\[\d{1,4}\]",
    re.IGNORECASE,
)
"""Enough of a statutory reference to override :data:`_DOCUMENT_SUBJECT`.

The casual contract template opens "This contract is drafted on the basis
that ... the Fair Work Act 2009 (Cth), the National Employment Standards and
the applicable Modern Award govern the employment". Its subject is the
contract; its content is a claim about which law applies, and the judge must
see it."""


class ClaimUnit(Protocol):
    """How a body of drafted text is cut into the things a judge rules on.

    The seam the case-law phase needs. A judgment is not cut into sentences -
    a holding runs across several and a numbered paragraph is the unit a court
    is cited by - so that phase registers a paragraph unit here. Nothing else
    in this module knows what a unit is: :class:`Claim` records which one
    produced it, and the judge prompt names it, so two unit types can coexist
    in one draft without either being special-cased.
    """

    @property
    def name(self) -> str:
        """What to call this unit in the judge prompt - "sentence"."""

    def split(self, text: str) -> list[tuple[int, int]]:
        """Character spans of ``text``, in order, one per candidate claim."""


@dataclass(frozen=True, slots=True)
class SentenceUnit:
    """One sentence, in a paragraph that has been unwrapped first.

    Templates are hard-wrapped, so a sentence routinely spans three source
    lines. Splitting on lines would cut claims in half and hand the judge
    fragments; splitting the *unwrapped* paragraph and mapping back to the
    original offsets keeps the spans usable for annotation.
    """

    name: str = "sentence"

    def split(self, text: str) -> list[tuple[int, int]]:
        spans: list[tuple[int, int]] = []
        for start, end in _paragraph_spans(text):
            block = text[start:end]
            cursor = 0
            for piece in _SENTENCE_END.split(block):
                if piece.strip():
                    lead = len(piece) - len(piece.lstrip())
                    spans.append((start + cursor + lead, start + cursor + len(piece.rstrip())))
                cursor += len(piece)
        return spans


@dataclass(frozen=True, slots=True)
class ParagraphUnit:
    """One blank-line separated block, ruled on whole.

    The unit for prose grounded in case law. A judgment supports a proposition
    by its ratio, which is carried by a passage rather than by any one
    sentence of it: cut into sentences, "His Honour rejected that
    construction." and "The section is therefore not engaged." are each
    unrulable on their own, and a judge asked about either in isolation has to
    answer UNSUPPORTED however well the paragraph as a whole carries it.
    """

    name: str = "paragraph"

    def split(self, text: str) -> list[tuple[int, int]]:
        spans: list[tuple[int, int]] = []
        for start, end in _paragraph_spans(text):
            block = text[start:end]
            lead = len(block) - len(block.lstrip())
            trail = len(block) - len(block.rstrip())
            if block.strip():
                spans.append((start + lead, end - trail))
        return spans


SENTENCE: ClaimUnit = SentenceUnit()
PARAGRAPH: ClaimUnit = ParagraphUnit()

#: Registered unit types, by name.
UNITS: dict[str, ClaimUnit] = {SENTENCE.name: SENTENCE, PARAGRAPH.name: PARAGRAPH}

#: Chooses the unit for one block of the draft. The seam the Phase 3 handover
#: asked for: ``split_claims`` took a single unit for the whole draft, and a
#: draft that cites both an Act and a judgment needs both - sentence-level for
#: statutory prose, paragraph-level where the support is a ratio. A selector
#: is called once per blank-line separated block and returns the unit that
#: block is cut with; the chosen unit's name is recorded on every claim it
#: produces, so the judge prompt names it and two kinds can coexist in one
#: draft without either being special-cased.
UnitSelector = Callable[[str], ClaimUnit]


def _paragraph_spans(text: str) -> list[tuple[int, int]]:
    """Spans of blank-line separated blocks, skipping blocks that are not prose."""
    spans: list[tuple[int, int]] = []
    offset = 0
    for block in re.split(r"\n[ \t]*\n", text):
        start, end = offset, offset + len(block)
        offset = end + 2  # the separator is at least "\n\n"; see _fix_offsets
        if block.strip():
            spans.append((start, end))
    return _fix_offsets(text, spans)


def _fix_offsets(text: str, spans: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """Re-anchor spans by searching forward, so a wider separator cannot shift them.

    ``re.split`` discards the separator and a blank line may carry trailing
    spaces, so arithmetic on the split pieces drifts. Annotation inserts at
    these offsets, and an offset that drifts inserts a marker into the middle
    of a word, so they are re-found in the source rather than computed.
    """
    fixed: list[tuple[int, int]] = []
    cursor = 0
    for start, end in spans:
        block = text[start:end]
        found = text.find(block, cursor)
        if found < 0:  # pragma: no cover - only reachable if text mutated
            found = start
        fixed.append((found, found + len(block)))
        cursor = found + len(block)
    return fixed


@dataclass(frozen=True, slots=True)
class Claim:
    """One atomic assertion from the draft, with where it sits in the text."""

    claim_id: str
    text: str
    start: int
    end: int
    unit: str = SENTENCE.name


@dataclass(frozen=True, slots=True)
class Ruling:
    """One validated verdict. Only ever produced by :func:`validate_verdicts`."""

    claim_id: str
    verdict: Verdict
    provision_ids: tuple[str, ...]
    reason: str

    @property
    def flagged(self) -> bool:
        return self.verdict in FLAGGED


@dataclass(frozen=True, slots=True)
class JudgeCall:
    """What one judge call cost, so the price of verification is reportable."""

    model: str
    seconds: float
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost_usd: float | None = None
    error: str = ""


@dataclass(frozen=True, slots=True)
class Verification:
    """The outcome of verifying one draft."""

    claims: tuple[Claim, ...]
    rulings: tuple[Ruling, ...]
    judge_model: str
    skipped_unsupplied: int = 0
    instructed: tuple[Claim, ...] = field(default_factory=tuple)
    call: JudgeCall | None = None
    notes: tuple[str, ...] = field(default_factory=tuple)

    @property
    def counts(self) -> dict[str, int]:
        tally: dict[str, int] = dict.fromkeys(VERDICTS, 0)
        for ruling in self.rulings:
            tally[ruling.verdict] += 1
        return tally

    @property
    def flagged(self) -> tuple[Ruling, ...]:
        return tuple(r for r in self.rulings if r.flagged)

    def claim(self, claim_id: str) -> Claim | None:
        return next((c for c in self.claims if c.claim_id == claim_id), None)


class JudgeError(RuntimeError):
    """The judge could not be reached, or returned something unusable.

    Never raised out of :func:`verify_draft`: it is caught there and turned
    into an UNSUPPORTED verdict on every claim. It exists so the *reason* for
    failing closed reaches the practitioner instead of being swallowed.
    """


#: The judge seam. Takes the assembled prompt, returns the raw response body
#: and what the call cost. Injected in tests; defaults to OpenRouter.
JudgeFn = Callable[[str], tuple[str, JudgeCall]]


# --- step 1: split the draft into claims (code) ----------------------------


def _verifiable_body(text: str) -> str:
    """The drafted prose, with everything code generated taken out of it.

    Two removals. The trailing blocks - the citation list and the closing
    blocks - are cut off at the first heading that starts them. The outline's
    own scaffolding lines are *blanked*, not deleted: every character index in
    what comes back still points at the same character of the original, so
    :func:`annotate` can write a marker at a claim's end offset and land in
    the right place.
    """
    cut = len(text)
    for heading in TRAILING_HEADINGS:
        found = text.find(f"\n{heading}")
        if found >= 0:
            cut = min(cut, found)
    body = text[:cut]
    return "\n".join(
        " " * len(line) if _GENERATED_LINE.match(line) else line for line in body.split("\n")
    )


def _is_claim(sentence: str) -> bool:
    """Does this fragment assert something a provision could support?"""
    stripped = sentence.strip()
    if not stripped:
        return False
    if _HEADING.match(stripped) or _RULE.match(stripped):
        return False
    if _BOLD_FIELD.match(stripped) and not stripped.rstrip().endswith("."):
        return False
    if stripped.rstrip().endswith(":"):
        # A label introducing a block - "Signed by the Employee:" - asserts
        # nothing on its own.
        return False
    naked = _LIST_MARKER.sub("", stripped)
    if _DOCUMENT_SUBJECT.match(naked) and not _LEGAL_REFERENCE.search(naked):
        return False
    return len(re.findall(r"[A-Za-z][\w'-]*", naked)) >= MIN_CLAIM_WORDS


def split_claims(
    draft_text: str, *, unit: ClaimUnit | UnitSelector = SENTENCE
) -> tuple[tuple[Claim, ...], int]:
    """Cut a draft into atomic claims. Returns the claims and how many were skipped.

    ``unit`` is either one :class:`ClaimUnit` applied to the whole draft, or a
    :data:`UnitSelector` called once per blank-line separated block, which is
    how a draft that mixes statutory prose and case-law discussion is cut with
    the right unit for each. A unit is recognised by having a ``split``
    method; anything else callable is treated as a selector.

    A claim carrying a ``[MISSING: ...]`` marker is skipped rather than
    judged. Its operative value was never supplied, so there is nothing for a
    provision to support, and it is already in front of the practitioner under
    OPEN ITEMS. The count comes back so the VERIFICATION section can say how
    many were set aside - a skip that is not reported is a silent one, and
    this module does not have silent ones.
    """
    body = _verifiable_body(draft_text or "")
    claims: list[Claim] = []
    skipped = 0
    for chosen, start, end in _spans(body, unit):
        sentence = body[start:end]
        if not _is_claim(sentence):
            continue
        if MISSING_RE.search(sentence):
            skipped += 1
            continue
        claims.append(
            Claim(
                claim_id=f"c{len(claims) + 1}",
                text=" ".join(sentence.split()),
                start=start,
                end=end,
                unit=chosen.name,
            )
        )
    return tuple(claims), skipped


def _spans(body: str, unit: ClaimUnit | UnitSelector) -> list[tuple[ClaimUnit, int, int]]:
    """Every candidate span of ``body``, each with the unit that produced it."""
    if hasattr(unit, "split"):
        fixed: ClaimUnit = unit  # type: ignore[assignment]
        return [(fixed, start, end) for start, end in fixed.split(body)]
    select: UnitSelector = unit
    out: list[tuple[ClaimUnit, int, int]] = []
    for start, end in _paragraph_spans(body):
        block = body[start:end]
        chosen = select(block)
        # The chosen unit is applied to the block alone, so its offsets are
        # block-relative and are shifted back. Annotation writes at these
        # offsets and an offset that drifts inserts a marker mid-word.
        out += [(chosen, start + a, start + b) for a, b in chosen.split(block)]
    return out


